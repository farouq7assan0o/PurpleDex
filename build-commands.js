const fs = require('fs');
const path = require('path');

function buildCommands() {
    const commandsDir = path.join(__dirname, 'commands');
    const allCommands = [];

    function walkDir(dir) {
        const entries = fs.readdirSync(dir, { withFileTypes: true });
        for (const entry of entries) {
            const fullPath = path.join(dir, entry.name);
            if (entry.isDirectory()) {
                walkDir(fullPath);
            } else if (entry.isFile() && entry.name.endsWith('.json')) {
                const raw = fs.readFileSync(fullPath, 'utf8');
                let cmd;
                try {
                    cmd = JSON.parse(raw);
                } catch (e) {
                    console.error('Invalid JSON in ' + fullPath + ': ' + e.message);
                    process.exit(1);
                }
                // Tombstoned cards (source files can't be deleted on the mounted drive,
                // so a retired card is overwritten with {"_ignore":true}).
                if (cmd && cmd._ignore) continue;
                allCommands.push(cmd);
            }
        }
    }

    walkDir(commandsDir);

    // Deduplicate by id, merge certifications
    const map = new Map();
    for (const cmd of allCommands) {
        const key = cmd.id || cmd.command;
        if (map.has(key)) {
            const existing = map.get(key);
            const certs = new Set([...(existing.certifications || []), ...(cmd.certifications || [])]);
            existing.certifications = Array.from(certs);
            if (cmd.notes && cmd.notes !== existing.notes) {
                existing.notes = (existing.notes || '') + ' | ' + cmd.notes;
            }
        } else {
            map.set(key, cmd);
        }
    }

    const commands = Array.from(map.values());
    // Normalize: every card has a type; default to "command" so all 376 existing cards stay valid.
    commands.forEach(c => { if (!c.type) c.type = 'command'; });
    commands.sort((a, b) => a.name.localeCompare(b.name));

    const output = {
        commands: commands,
        totalCommands: commands.length,
        buildDate: new Date().toISOString(),
        certifications: [...new Set(commands.flatMap(c => c.certifications || []))].sort(),
        types: [...new Set(commands.map(c => c.type))].sort()
    };

    const outPath = path.join(__dirname, 'js', 'commands.js');
    const BANNER =
        '// AUTO-GENERATED by build-commands.js from commands/**/*.json - DO NOT EDIT BY HAND.\n' +
        '// Hand edits here are silently overwritten (and permanently lost) on the next build.\n' +
        '// To change a card, edit its JSON under commands/ then run: node build-commands.js\n';
    const body = BANNER + 'const COMMAND_DATA = ' + JSON.stringify(output, null, 2) + ';';

    // --check: don't write. Compare a fresh build against the committed bundle and FAIL on drift.
    // This is the tripwire for the classic data-loss bug: content that lives only in commands.js
    // (a hand edit) but not in the JSON source. It shows up here as drift BEFORE a rebuild wipes it.
    if (process.argv.includes('--check')) {
        let existing = null;
        try {
            const raw = fs.readFileSync(outPath, 'utf8');
            const marker = 'const COMMAND_DATA = ';
            const jsonStr = raw.slice(raw.indexOf(marker) + marker.length).replace(/;\s*$/, '');
            existing = JSON.parse(jsonStr);
        } catch (e) {
            console.error('DRIFT CHECK FAIL: cannot read/parse js/commands.js (' + e.message + '). Run: node build-commands.js');
            process.exit(1);
        }
        // Compare the card payload only; buildDate legitimately changes every build.
        const a = JSON.stringify(existing.commands), b = JSON.stringify(output.commands);
        if (a !== b || existing.totalCommands !== output.totalCommands) {
            console.error('DRIFT CHECK FAIL: js/commands.js does not match a fresh build from commands/**.');
            console.error('  bundle cards: ' + (existing.commands ? existing.commands.length : '??') + '  |  source cards: ' + output.commands.length);
            console.error('  Either the bundle was hand-edited (move those changes into the JSON source or they will be LOST),');
            console.error('  or it is stale. Regenerate with: node build-commands.js');
            process.exit(1);
        }
        console.log('DRIFT CHECK PASS: js/commands.js is in sync with commands/** (' + output.commands.length + ' cards).');
        return;
    }

    fs.writeFileSync(outPath, body);

    // --- Coverage index: technique -> detections, data_source -> techniques ---
    const coverage = { techniques: {}, data_sources: {}, cards_with_detections: 0, total_detections: 0 };
    for (const cmd of commands) {
        const dets = cmd.defense && Array.isArray(cmd.defense.detections) ? cmd.defense.detections : [];
        if (dets.length === 0) continue;
        coverage.cards_with_detections++;
        coverage.total_detections += dets.length;
        for (const det of dets) {
            // technique -> detection index
            for (const tid of (det.attack || [])) {
                if (!coverage.techniques[tid]) coverage.techniques[tid] = { detections: [], platforms: new Set(), data_sources: new Set(), best_fidelity: null };
                const t = coverage.techniques[tid];
                t.detections.push({ card_id: cmd.id, name: det.name, platform: det.platform, fidelity: det.fidelity, data_source: det.data_source });
                t.platforms.add(det.platform);
                t.data_sources.add(det.data_source);
                const fRank = { behavioral: 3, signature: 2, telemetry: 1 };
                if (!t.best_fidelity || (fRank[det.fidelity] || 0) > (fRank[t.best_fidelity] || 0)) t.best_fidelity = det.fidelity;
            }
            // data_source -> technique index
            if (det.data_source) {
                if (!coverage.data_sources[det.data_source]) coverage.data_sources[det.data_source] = new Set();
                for (const tid of (det.attack || [])) coverage.data_sources[det.data_source].add(tid);
            }
        }
        // visibility enrichment
        const vis = cmd.defense && cmd.defense.visibility;
        if (vis && vis.requires) {
            for (const ds of vis.requires) {
                if (!coverage.data_sources[ds]) coverage.data_sources[ds] = new Set();
            }
        }
    }
    // serialize Sets
    for (const t of Object.values(coverage.techniques)) { t.platforms = [...t.platforms]; t.data_sources = [...t.data_sources]; }
    for (const [k, v] of Object.entries(coverage.data_sources)) coverage.data_sources[k] = [...v];

    const covPath = path.join(__dirname, 'js', 'coverage.json');
    fs.writeFileSync(covPath, JSON.stringify(coverage, null, 2));

    console.log('Build complete: ' + commands.length + ' commands from ' + allCommands.length + ' sources.');
    console.log('Coverage index: ' + coverage.cards_with_detections + ' cards, ' + coverage.total_detections + ' structured detections, ' +
        Object.keys(coverage.techniques).length + ' techniques, ' + Object.keys(coverage.data_sources).length + ' data sources.');
    console.log('Certifications: ' + output.certifications.join(', '));
    console.log('Types: ' + output.types.map(t => t + '=' + commands.filter(c => c.type === t).length).join(', '));
}

buildCommands();

// Auto-validate after every build so problems can never slip in silently. The report prints
// here; the build still succeeds (commands.js was already written). Use `node validate.js`
// directly (its exit code) to gate CI. Skip with SKIP_VALIDATE=1.
if (!process.env.SKIP_VALIDATE && !process.argv.includes('--check')) {
    try {
        require('child_process').execSync('node ' + require('path').join(__dirname, 'validate.js'),
            { stdio: 'inherit' });
    } catch (e) {
        // validate.js exits non-zero when it finds issues - that's expected; the report already
        // printed. Don't fail the build itself.
    }
}
